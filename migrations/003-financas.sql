-- A recorrência tem um cursor próprio: editar/excluir um lançamento mensal não o recria.
CREATE TABLE IF NOT EXISTS public.despesa_recorrencia (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  despesa_origem_id INTEGER UNIQUE REFERENCES public.despesa(id) ON DELETE SET NULL,
  ultima_competencia DATE NOT NULL
);
ALTER TABLE public.despesa ADD COLUMN IF NOT EXISTS recorrencia_id INTEGER REFERENCES public.despesa_recorrencia(id);
ALTER TABLE public.despesa ADD COLUMN IF NOT EXISTS competencia DATE;
CREATE UNIQUE INDEX IF NOT EXISTS despesa_recorrencia_competencia_key
  ON public.despesa (recorrencia_id, competencia);

CREATE OR REPLACE FUNCTION public.registrar_recorrencia_despesa() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  inicio DATE := date_trunc('month', NEW.data)::date;
BEGIN
  -- Somente o cadastro original controla a série; cópias mensais não geram outras séries.
  IF NEW.recorrencia_id IS NOT NULL OR NEW.agendamento_id IS NOT NULL OR NEW.tipo <> 'fixo' THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.tipo <> 'fixo' THEN
    -- Ao ativar/reativar, não cobra os meses em que a despesa era variável.
    inicio := GREATEST(inicio, date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo')::date);
  END IF;
  INSERT INTO public.despesa_recorrencia (despesa_origem_id, ultima_competencia)
  VALUES (NEW.id, inicio)
  ON CONFLICT (despesa_origem_id) DO UPDATE
    SET ultima_competencia = GREATEST(public.despesa_recorrencia.ultima_competencia, EXCLUDED.ultima_competencia);
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS registrar_recorrencia_despesa ON public.despesa;
CREATE TRIGGER registrar_recorrencia_despesa AFTER INSERT OR UPDATE ON public.despesa
  FOR EACH ROW EXECUTE FUNCTION public.registrar_recorrencia_despesa();

-- Inclui despesas fixas cadastradas antes desta atualização sem reiniciar séries existentes.
INSERT INTO public.despesa_recorrencia (despesa_origem_id, ultima_competencia)
SELECT id, date_trunc('month', data)::date FROM public.despesa
 WHERE tipo = 'fixo' AND agendamento_id IS NULL AND recorrencia_id IS NULL
ON CONFLICT (despesa_origem_id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.gerar_despesas_fixas(
  ate DATE DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo')::date
) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE
  serie RECORD;
  mes DATE;
  vencimento DATE;
  criadas INTEGER := 0;
BEGIN
  IF ate IS NULL THEN RAISE EXCEPTION 'Informe a data limite da recorrência.'; END IF;
  -- Serializa servidores/requisições concorrentes durante toda a transação.
  PERFORM pg_advisory_xact_lock(734920163);
  FOR serie IN
    SELECT r.id, r.ultima_competencia, d.nome, d.valor, d.data
      FROM public.despesa_recorrencia r JOIN public.despesa d ON d.id = r.despesa_origem_id
     WHERE d.tipo = 'fixo'
       AND r.ultima_competencia < date_trunc('month', ate)::date
     ORDER BY r.id FOR UPDATE OF r
  LOOP
    mes := (serie.ultima_competencia + interval '1 month')::date;
    WHILE mes <= date_trunc('month', ate)::date LOOP
      -- Mantém o dia original, inclusive após fevereiro ou meses de 30 dias.
      vencimento := mes + (LEAST(EXTRACT(day FROM serie.data)::int,
        EXTRACT(day FROM mes + interval '1 month - 1 day')::int) - 1);
      EXIT WHEN vencimento > ate;
      INSERT INTO public.despesa (nome, valor, tipo, data, recorrencia_id, competencia)
      VALUES (serie.nome, serie.valor, 'fixo', vencimento, serie.id, mes);
      UPDATE public.despesa_recorrencia SET ultima_competencia = mes WHERE id = serie.id;
      criadas := criadas + 1;
      mes := (mes + interval '1 month')::date;
    END LOOP;
  END LOOP;
  RETURN criadas;
END $$;
