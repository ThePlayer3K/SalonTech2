-- Schema convertido do export do Supabase para PostgreSQL/Render.
-- Execute no banco já criado pelo Render com:
-- psql "$DATABASE_URL" -f schema.sql

-- 1. TABELA DE FUNCIONÁRIOS
CREATE TABLE IF NOT EXISTS public.funcionario (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  cpf VARCHAR(14) UNIQUE,
  cargo VARCHAR(80),
  tipo_pagamento VARCHAR(30),
  salario NUMERIC(10, 2),
  telefone VARCHAR(20)
);

-- 2. TABELA DE CLIENTES
CREATE TABLE IF NOT EXISTS public.cliente (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  cpf VARCHAR(14) UNIQUE,
  telefone VARCHAR(20),
  email VARCHAR(255)
);

-- 3. FORMAS DE PAGAMENTO
CREATE TABLE IF NOT EXISTS public.forma_pagamento (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(80) NOT NULL
);

-- 4. DESPESAS
CREATE TABLE IF NOT EXISTS public.despesa (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  data DATE,
  valor NUMERIC(10, 2)
);

-- 5. PRODUTOS
CREATE TABLE IF NOT EXISTS public.produto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  qtd_estoque INTEGER DEFAULT 0,
  categoria VARCHAR(80) NOT NULL
);

-- 6. USUÁRIOS
-- O schema original não possui e-mail. O login da aplicação usa usuario.nome.
-- tipo permanece para compatibilidade; papel define a hierarquia de acesso.
CREATE TABLE IF NOT EXISTS public.usuario (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  senha VARCHAR(255) NOT NULL,
  tipo VARCHAR(1) NOT NULL CHECK (tipo IN ('A', 'F')),
  funcionario_id INTEGER UNIQUE REFERENCES public.funcionario(id),
  papel VARCHAR(20) NOT NULL DEFAULT 'profissional'
);

ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS papel VARCHAR(20);
UPDATE public.usuario
   SET papel = CASE WHEN tipo = 'A' THEN 'admin' ELSE 'profissional' END
 WHERE papel IS NULL;
ALTER TABLE public.usuario ALTER COLUMN papel SET DEFAULT 'profissional';
ALTER TABLE public.usuario ALTER COLUMN papel SET NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'usuario_papel_check' AND conrelid = 'public.usuario'::regclass
  ) THEN
    ALTER TABLE public.usuario ADD CONSTRAINT usuario_papel_check CHECK (papel IN ('master', 'admin', 'profissional'));
  END IF;
END $$;

-- Vincula funcionários a contas legadas que ainda não possuíam associação.
DO $$
DECLARE
  conta RECORD;
  novo_funcionario_id INTEGER;
BEGIN
  FOR conta IN SELECT id, nome, papel FROM public.usuario WHERE funcionario_id IS NULL LOOP
    INSERT INTO public.funcionario (nome, cargo)
    VALUES (
      conta.nome,
      CASE WHEN conta.papel IN ('admin', 'master') THEN 'Administrador' ELSE 'Profissional de beleza' END
    )
    RETURNING id INTO novo_funcionario_id;

    UPDATE public.usuario SET funcionario_id = novo_funcionario_id WHERE id = conta.id;
  END LOOP;
END $$;

ALTER TABLE public.usuario ALTER COLUMN funcionario_id SET NOT NULL;
UPDATE public.funcionario f
   SET cargo = 'Administrador master'
  FROM public.usuario u
 WHERE u.funcionario_id = f.id AND u.papel = 'master';

-- 7. SERVIÇOS
CREATE TABLE IF NOT EXISTS public.servico (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  duracao INTEGER,
  categoria VARCHAR(80) NOT NULL,
  valor NUMERIC(10, 2) NOT NULL,
  funcionario_id INTEGER NOT NULL REFERENCES public.funcionario(id),
  percentual_comissao NUMERIC(5, 2) NOT NULL
);

-- 8. AGENDAMENTOS
CREATE TABLE IF NOT EXISTS public.agendamento (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER REFERENCES public.cliente(id),
  forma_pag_id INTEGER REFERENCES public.forma_pagamento(id),
  situacao VARCHAR(30),
  data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  observacoes TEXT,
  servico_id INTEGER NOT NULL REFERENCES public.servico(id),
  valor_total NUMERIC(10, 2)
);

-- 9. ÍNDICES PARA AS RELAÇÕES MAIS CONSULTADAS
CREATE INDEX IF NOT EXISTS idx_usuario_nome ON public.usuario (nome);
CREATE INDEX IF NOT EXISTS idx_servico_funcionario_id ON public.servico (funcionario_id);
CREATE INDEX IF NOT EXISTS idx_agendamento_cliente_id ON public.agendamento (cliente_id);
CREATE INDEX IF NOT EXISTS idx_agendamento_servico_id ON public.agendamento (servico_id);
CREATE INDEX IF NOT EXISTS idx_agendamento_data_hora ON public.agendamento (data_hora);
